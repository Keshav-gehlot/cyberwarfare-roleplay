#!/usr/bin/env python3
"""
sar_jitter_analyzer.py: detector for fake satellite or radar telemetry.

Runs with Python 3 only. No packages or network needed.

A real satellite downlink has random phase noise from heat, the atmosphere
and the oscillator. Generated or replayed data is often smoother than that.
This script looks at the last 50 phase samples and calculates:
  * jitter sigma: standard deviation of the change between samples
  * Shannon entropy: H = -sum(p * log2(p)) over changes rounded to 0.01 rad
If either is below its threshold (0.07 rad and 2.5 bits), the feed is
flagged as synthetic.

Where it runs: at the satellite ground decoder, before the data reaches
operators or automated systems.

The real and fake signals in this demo are generated by the script, not
captured from a radio link.

Limits:
  * Thresholds are fixed. Real ones depend on link quality, satellite
    elevation and weather.
  * An attacker can add noise that matches a real downlink and pass this
    check. Comparing with a second source (passive RF, orbital data) is
    needed.
  * Only phase is checked. Amplitude, Doppler and timing are ignored.
"""

import math
import random
import collections
from typing import Any, Deque, Dict, Tuple


class SARJitterAnalyzer:
    """Sliding-window detector for synthetically smooth telemetry."""

    def __init__(self, window: int = 50, sigma_min: float = 0.07,
                 entropy_min: float = 2.5) -> None:
        self.window = window
        self.sigma_min = sigma_min
        self.entropy_min = entropy_min
        self.history: Deque[float] = collections.deque(maxlen=window)

    @staticmethod
    def _entropy(values) -> float:
        """Shannon entropy (bits) over values quantised to 2 decimals."""
        if not values:
            return 0.0
        counts = collections.Counter(round(v, 2) for v in values)
        n = len(values)
        h = -sum((c / n) * math.log2(c / n) for c in counts.values())
        return h + 0.0 if h != 0 else 0.0  # normalise -0.0 -> 0.0

    def ingest(self, phase_rad: float) -> Tuple[bool, Dict[str, Any]]:
        """Add one phase sample; return (is_synthetic, report)."""
        self.history.append(phase_rad)
        if len(self.history) < self.window:
            return False, {"status": "WARMING_UP", "fill": len(self.history)}

        phases = list(self.history)
        deltas = [phases[i] - phases[i - 1] for i in range(1, len(phases))]
        mean = sum(deltas) / len(deltas)
        sigma = math.sqrt(sum((d - mean) ** 2 for d in deltas) / len(deltas))
        entropy = self._entropy(deltas)

        synthetic = False
        reason = "Phase noise in normal range"
        if sigma < self.sigma_min:
            synthetic = True
            reason = f"Phase jitter too smooth: sigma={sigma:.4f} < {self.sigma_min}"
        elif entropy < self.entropy_min:
            synthetic = True
            reason = f"Delta distribution too regular: H={entropy:.2f} < {self.entropy_min}"

        return synthetic, {
            "status": "ANALYZED",
            "synthetic": synthetic,
            "sigma": round(sigma, 4),
            "entropy": round(entropy, 2),
            "reason": reason,
        }


def run_stream(analyzer: SARJitterAnalyzer, generator) -> Dict[str, Any]:
    report: Dict[str, Any] = {}
    for sample in generator:
        _, report = analyzer.ingest(sample)
    return report


def authentic_stream(n: int, rng: random.Random):
    """Natural feed: steady drift + Gaussian phase noise."""
    phase = 1.57
    for _ in range(n):
        phase += 0.02 + rng.gauss(0.0, 0.12)
        yield phase


def synthetic_stream(n: int):
    """Spoofed feed: smooth interpolation with faint deterministic ripple."""
    phase = 1.57
    for step in range(n):
        phase += 0.02 + 0.005 * math.sin(step / 3.0)
        yield phase


def _print(label: str, r: Dict[str, Any]) -> None:
    flag = "SYNTHETIC" if r.get("synthetic") else "AUTHENTIC"
    print(f"  [{flag:<9}] {label}")
    print(f"      sigma={r['sigma']}  entropy={r['entropy']} bits")
    print(f"      verdict: {r['reason']}")


def main() -> None:
    print("=" * 70)
    print(" sar_jitter_analyzer.py: fake satellite telemetry detector")
    print("=" * 70)
    rng = random.Random(42)  # fixed seed -> reproducible demo output

    print("\n[NORMAL] Real downlink with natural phase noise")
    a = SARJitterAnalyzer()
    _print("NavIC downlink window", run_stream(a, authentic_stream(50, rng)))

    print("\n[ATTACK] Generated SAR data injected at the ground station")
    b = SARJitterAnalyzer()
    _print("compromised ground station", run_stream(b, synthetic_stream(50)))

    print("=" * 70)


if __name__ == "__main__":
    main()
